Ayatam.ACG.findCharacter = function(charaName) {
    var result = [];
    if(this.loadedCharacters()) {
        if(this.loadedCharacters().length > 0) {
            this.loadedCharacters().forEach(chara => {
                if(chara) {
                    if(chara.includes(charaName)) {
                        result.push(chara);
                    };
                };
            });
        };
    };
    return result;
};

