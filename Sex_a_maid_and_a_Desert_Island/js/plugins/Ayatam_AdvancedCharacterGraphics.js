        initialize() {
            this._followDistance = Ayatam.ACG.GlobalSettings.pixelFollowerDistance;
            if(this._followDistance instanceof String) this._followDistance = 1.8125;
        }
        //--------------------------------------------------------------------------
        // ● コサイン
        //-------------------------------------------------------------------------
        cos(org,pos) {
            var orgNormalize = org.velocity === 0.0 ? this.pixelPosByVelDir(1.0 , org.dir) : this.pixelPos((1.0 / org.velocity) * org.x,(1.0 / org.velocity) * org.y);
            var posNormalize = pos.velocity === 0.0 ? this.pixelPosByVelDir(1.0 , pos.dir) : this.pixelPos((1.0 / pos.velocity) * pos.x,(1.0 / pos.velocity) * pos.y);
            return orgNormalize.x * posNormalize.x + orgNormalize.y * posNormalize.y;
        };
        //--------------------------------------------------------------------------
        // ● クロス
        //-------------------------------------------------------------------------
        cross(org,pos) {
            var orgNormalize = org.velocity === 0.0 ? this.pixelPosByVelDir(1.0 , org.dir) : this.pixelPos((1.0 / org.velocity) * org.x,(1.0 / org.velocity) * org.y);
            return orgNormalize.x * pos.y - orgNormalize.y * pos.x;
        };
        //--------------------------------------------------------------------------
        // ● 建造物回避
        //-------------------------------------------------------------------------
        perp(org,vel) {
            var orgNormalize = org.velocity === 0.0 ? this.pixelPosByVelDir(0.0 , org.dir + Math.PI / 2.0) : this.pixelPos(-org.y,org.x);
            return orgNormalize.velocity === 0.0 ? this.pixelPosByVelDir(vel , orgNormalize.dir) : this.pixelPos((vel / orgNormalize.velocity) * orgNormalize.x,(vel / orgNormalize.velocity) * orgNormalize.y);
        };
