var _Ayatam_Acg_DataManager_extractSaveContents = DataManager.extractSaveContents;
DataManager.extractSaveContents = function(contents) {
    this.acgCheckNewContents(contents);
    _Ayatam_Acg_DataManager_extractSaveContents.call(this,contents);
    this.acgRestoreActors();
    this.acgRestoreFollowers();
};

DataManager.acgCheckNewContents = function(contents) {
    if(!contents.party.acgRegionList) {
        contents.party.createAcgRegionList();
    };
    if(!contents.player.acgAutoDashDuration) {
        contents.player.setupAcgAutoDashMode();
    };
    if(Ayatam.ACG.GlobalSettings.pixelMovements && !contents.player._acgPixelPos) {
        contents.player.initAcgPixelMovements();
    };
};

DataManager.acgRestoreActors = function() {
    $dataActors.forEach(function(actor) { if(actor) { if($gameActors.actor(actor.id)) { $gameActors.actor(actor.id).acgNoteLoaded = false; $gameActors.actor(actor.id).createAcgRoutSetup(); $gameActors.actor(actor.id).getAcgCharacterNote(); } } });
};

DataManager.acgRestoreFollowers = function() {
    $gamePlayer._followers.initialize();
    $gamePlayer._followers._data.forEach(follower => {
        if(follower) {
            follower.copyPosition($gamePlayer);
        };
    });
    $gamePlayer.refresh();
};

var _Ayatam_Acg_DataManager_makeSavefileInfo = DataManager.makeSavefileInfo;
DataManager.makeSavefileInfo = function() {
    var loadAcg = false;
    var acgInfo = _Ayatam_Acg_DataManager_makeSavefileInfo.call(this);
    if(Ayatam.ACG.GlobalSettings.useCharacterFunctions) {
        if(Ayatam.ACG.GlobalSettings.functionSw > 0) {
            if($gameSwithes.value(Ayatam.ACG.GlobalSettings.functionSw)) {
                loadAcg = true;
            };
        }else{
            loadAcg = true;
        };
    };
    if(loadAcg) {
        acgInfo.acgCharacters = $gameParty.battleMembers().map(function(actor) {
            return [actor.getAcgBaseCharacter().name,actor.getAcgBaseCharacter().index,actor.getAcgActorSet()];
        });
    };
    return acgInfo;
};
