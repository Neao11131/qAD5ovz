Ayatam.ACG.loadImgFile = function() {
    this._loadedCharacters = [];
    if(this._imgFullPath === undefined) this._imgFullPath = this.getImgPath();
    var fs = require('fs');
    if(Utils.RPGMAKER_NAME === "MV") {
        var ext = Decrypter.hasEncryptedImages ? '.rpgmvp' : '.png';
    }else if(Utils.RPGMAKER_NAME === "MZ"){
        var ext = Utils.hasEncryptedImages() ? '.png_' : '.png';
    };
    var dir = this._imgFullPath + 'characters/';
    var list = fs.readdirSync(dir);
    if(list.length <= 0) return;
    list.forEach(file => {
        if(file) {
            var fullPath = dir + file;
            var original = this.hasExt(file,ext);
            if(!fs.statSync(fullPath).isDirectory() && original) {
                ImageManager.loadCharacter(original);
                this._loadedCharacters.push(original);
            };
        };
    });
};

