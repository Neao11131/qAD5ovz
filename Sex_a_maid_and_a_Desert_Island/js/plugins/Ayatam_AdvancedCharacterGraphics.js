Ayatam.ACG.getAcgOjectsNote = function(obj) {
    if(obj.acgNoteLoaded !== undefined) return;
    obj.acgNoteLoaded = true;
    obj.acgCharacterList = [];
    var lists = obj.note.split(/[\r\n]+/);
    var checkCharacterInfo = false;
    lists.forEach(note => {
        if(note !== "") {
            if(note !== "") {
                //装備時の歩行グラフィック設定
                if(note.match(/<acg characterList>/i)) checkCharacterInfo = true;
                if(note.match(/<\/acg characterList>/i)) checkCharacterInfo = false;
                if(checkCharacterInfo) {
                    if(note.match(/(.*): (.*)/i)) {
                        var result = note.match(/(.*): (.*)/i);
                        var actorId = JSON.parse(JSON.stringify(result[1],(key,value)=>{
                            try{return JSON.parse(value);} catch (e) {}
                            return value;
                            }
                        ));
                        var charaName = JSON.parse(JSON.stringify(result[2],(key,value)=>{
                            try{return JSON.parse(value);} catch (e) {}
                            return value;
                            }
                        ));
                        obj.acgCharacterList[actorId] = { name: charaName };
                    };
                };
            };
        };
    });
};
